# Logical Operator

print(not False)        # not means opposite of False
print(not True)         # not means opposite of True

a = 50
b = 30
print(not (a > b))      # Opposite of True

val1 = True         # AND operator gives True only when
val2 = True         # all the conditions are true.
print("AND Operator:",val1 and val2)    

sub1 = True         # OR operator gives True when
sub2 = False        # any of the condition is true
print("OR Operator:",sub1 or sub2)