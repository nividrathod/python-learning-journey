# Arithmetic Operators
a = 5
b = 2
print(a + b)        # Addition
print(a - b)        # Substraction
print(a * b)        # Multiplication
print(a / b)        # Divide
print(a % b)        # Modules
print(a ** b)       # Power

# Relational Operator
num1 = 55
num2 = 33

print(a == b)       # Equal
print(a != b)       # Not Equal
print(a > b)        # Greater than
print(a >= b)       # Greater than & Equal
print(a < b)        # Less than
print(a <= b)       # Less than & Equal

